import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import prettier from "prettier"

const sources = {
    en: {
        url: "https://raw.githubusercontent.com/unicode-org/cldr/release-48-2/common/main/en.xml",
        filename: "en.xml",
        sha256: "67607f4c9cf57157e70564987d8ae92a9ddcd73c00a2f1cd6abf79524a969cbd",
    },
    km: {
        url: "https://raw.githubusercontent.com/unicode-org/cldr/release-48-2/common/main/km.xml",
        filename: "km.xml",
        sha256: "aeae2c7371d91146ffe626ef4e038d443697055b106b48d964336428541531b8",
    },
    off: {
        url: "https://raw.githubusercontent.com/openfoodfacts/openfoodfacts-server/0ab188b448314571fc59afa364274e906a3d60d3/taxonomies/countries.txt",
        filename: "countries-pinned.txt",
        sha256: "1a14ba7644b12dbbb31d07e3949b39a41dcbf1ad13bf9664480160ed13b763ca",
    },
}

const sourceDirIndex = process.argv.indexOf("--source-dir")
const sourceDir = sourceDirIndex < 0 ? null : process.argv[sourceDirIndex + 1]
if (sourceDirIndex >= 0 && !sourceDir) {
    throw new Error("--source-dir requires a directory")
}

async function loadSource(source) {
    const bytes = sourceDir
        ? await readFile(resolve(sourceDir, source.filename))
        : Buffer.from(await (await fetch(source.url)).arrayBuffer())
    const digest = createHash("sha256").update(bytes).digest("hex")
    if (digest !== source.sha256) {
        throw new Error(`Source checksum mismatch: ${source.filename}`)
    }
    return bytes.toString("utf8")
}

function decodeXml(text) {
    return text
        .replaceAll("&amp;", "&")
        .replaceAll("&apos;", "'")
        .replaceAll("&quot;", '"')
        .replaceAll("&lt;", "<")
        .replaceAll("&gt;", ">")
}

function normalize(value) {
    return value
        .normalize("NFKD")
        .replace(/[\u0300-\u036f]/g, "")
        .replace(/[’‘]/g, "'")
        .replace(/[-_]+/g, " ")
        .replace(/\s+/g, " ")
        .trim()
        .toLowerCase()
}

function territories(xml) {
    const result = new Map()
    for (const match of xml.matchAll(
        /<territory\b([^>]*)>([^<]*)<\/territory>/g,
    )) {
        const code = match[1].match(/\btype="([^"]+)"/)?.[1]
        if (!code) continue
        const alt = match[1].match(/\balt="([^"]+)"/)?.[1]
        const value = decodeXml(match[2])
        const current = result.get(code)
        if (!current || !alt || (alt === "short" && /^(HK|MO)$/.test(code))) {
            result.set(code, value)
        }
    }
    return result
}

const [englishXml, khmerXml, offText] = await Promise.all([
    loadSource(sources.en),
    loadSource(sources.km),
    loadSource(sources.off),
])
const english = territories(englishXml)
const khmer = territories(khmerXml)
const codeByEnglishName = new Map(
    [...english].map(([code, name]) => [normalize(name), code]),
)
for (const match of englishXml.matchAll(
    /<territory\b([^>]*)>([^<]*)<\/territory>/g,
)) {
    const code = match[1].match(/\btype="([^"]+)"/)?.[1]
    if (code) codeByEnglishName.set(normalize(decodeXml(match[2])), code)
}
const aliases = new Map()
const ambiguous = new Set()
const recognized = []
const unmapped = []

for (const block of offText.split(/\n\s*\n/)) {
    const names = block.match(/^en: (.*)$/m)?.[1]?.split(", ")
    if (!names?.length) continue
    const sourceName = names[0]
    const rawCode = block.match(/^country_code_2:en: (.*)$/m)?.[1]
    const code =
        rawCode === "UK"
            ? "GB"
            : rawCode === "world"
              ? "001"
              : rawCode || codeByEnglishName.get(normalize(sourceName))
    const offKhmer = block.match(/^km: (.*)$/m)?.[1]
    const name =
        (code && khmer.get(code)) ||
        offKhmer ||
        (rawCode === "YU" ? "យូហ្គោស្លាវី" : undefined)
    if (!name) {
        unmapped.push(sourceName)
        continue
    }
    recognized.push(sourceName)
    for (const alias of names) {
        if (alias.replace(/[^A-Za-z]/g, "").length < 4) continue
        const key = normalize(alias)
        if (!key || ambiguous.has(key)) continue
        const previous = aliases.get(key)
        if (previous && previous !== name) {
            aliases.delete(key)
            ambiguous.add(key)
        } else {
            aliases.set(key, name)
        }
    }
}

for (const [code, englishName] of english) {
    const name = khmer.get(code)
    if (name && /^[A-Z]{2}$|^\d{3}$/.test(code)) {
        const key = normalize(englishName)
        if (!ambiguous.has(key)) aliases.set(key, name)
    }
}

const byName = Object.fromEntries(
    [...aliases].sort(([a], [b]) => a.localeCompare(b)),
)
const generated = `// Generated by scripts/generate-geographic-names.mjs. Do not edit by hand.
// CLDR 48.2: ${sources.km.url}
// Open Food Facts countries taxonomy: ${sources.off.url}
export const GEOGRAPHIC_NAMES_KM: Readonly<Record<string, string>> = ${JSON.stringify(byName, null, 4)}

export const RECOGNIZED_OFF_COUNTRY_NAMES = ${JSON.stringify(recognized.sort(), null, 4)} as const

export const UNMAPPED_OFF_COUNTRY_NAMES = ${JSON.stringify(unmapped.sort(), null, 4)} as const
`
const output = resolve(
    dirname(fileURLToPath(import.meta.url)),
    "../src/features/product/geographicNames.generated.ts",
)
const prettierConfig = (await prettier.resolveConfig(output)) ?? {}
await writeFile(
    output,
    await prettier.format(generated, { ...prettierConfig, filepath: output }),
)
console.log(
    `Generated ${aliases.size} aliases for ${recognized.length} Open Food Facts entries; ${unmapped.length} source entries retain Original Text.`,
)
